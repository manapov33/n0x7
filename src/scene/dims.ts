// Общие размеры сцены: чистый модуль, без Three.js.
export const PAGE_W = 3;
export const PAGE_H = 4;
export const FOV = 35;

/**
 * Телефон показывает кадр ролика центральной вырезкой разворота: в игре камера cover видит по высоте всю страницу
 * (4), а по ширине только PAGE_H·aspect (при 390/844 это ~31% разворота). Вырезка 5:8 даёт запас ~35% по ширине
 * и закрывает телефоны до соотношения 0.625 (браузер с видимой панелью — около 0.6).
 */
export const PHONE_CROP_ASPECT = 5 / 8;
/** Ширина вырезки телефона в мировых единицах (высота — PAGE_H). */
export const phoneCropWidth = (): number => PAGE_H * PHONE_CROP_ASPECT;
